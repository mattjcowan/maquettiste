#!/bin/sh
# Regenerates src/Maquettiste.Cli/Commands/ShippedSkills.cs: the sha256 of skills/maquettiste-modeling/SKILL.md, with LF line
# endings, at every v* tag that has the file. Before the skill carried a header, `maquettiste init --skill` wrote exactly those
# bytes, so the table is how a newer CLI recognizes an untouched copy of an older release (Commands/AgentSetup.cs). A copy written
# with the header carries its own hash and needs no entry; the table still lists every tag so it stays complete.
#
# Run it from any folder of the repository after tagging a release (fetch the tags first), then build and commit the result:
#   git fetch --tags && sh skills/shipped-skills.sh
set -eu
root=$(git rev-parse --show-toplevel)
out="$root/src/Maquettiste.Cli/Commands/ShippedSkills.cs"
source=skills/maquettiste-modeling/SKILL.md

if command -v sha256sum >/dev/null 2>&1; then
  hash() { sha256sum | cut -c1-64; }
else
  hash() { shasum -a 256 | cut -c1-64; }
fi

rows=$(mktemp)
trap 'rm -f "$rows"' EXIT
for tag in $(git -C "$root" tag -l 'v*' --sort=v:refname); do
  git -C "$root" cat-file -e "$tag:$source" 2>/dev/null || continue
  # The CLI writes the embedded file with CRLF replaced by LF (the file has never had a byte order mark).
  sum=$(git -C "$root" show "$tag:$source" | sed 's/\r$//' | hash)
  printf '        ("%s", "%s"),\n' "${tag#v}" "$sum" >>"$rows"
done

{
  cat <<'EOF'
namespace Maquettiste.Cli.Commands;

// Generated by skills/shipped-skills.sh from the release tags; do not edit by hand.

/// <summary>
/// The modeling skill each release shipped: the sha256 of <c>skills/maquettiste-modeling/SKILL.md</c> with LF line endings, which is
/// what <c>maquettiste init --skill</c> of a release before the skill header wrote. <see cref="AgentSetup"/> rewrites a copy whose
/// bytes match one of these; any other copy without a valid header was edited by hand.
/// </summary>
internal static class ShippedSkills
{
    /// <summary>The release (without the <c>v</c> of its tag) and the hash, lowercase hex, in tag order.</summary>
    public static readonly IReadOnlyList<(string Version, string Sha256)> Releases =
    [
EOF
  cat "$rows"
  cat <<'EOF'
    ];
}
EOF
} >"$out"
echo "wrote $out ($(wc -l <"$rows" | tr -d ' ') releases)"
