        Assert.Same(first, second);
        var d = first.Diagnostics[0];
        Assert.Equal("MQ6003", d.Rule);
        Assert.Equal(2, d.Line);
        Assert.True(d.Column >= 10, "column " + d.Column);
        Assert.Equal(".maquettiste/templates/cache/bad.scriban", d.FilePath);
    }

