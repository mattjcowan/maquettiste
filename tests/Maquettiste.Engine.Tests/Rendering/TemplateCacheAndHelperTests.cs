    public void Template_files_must_be_utf8_and_lose_their_bom_and_crlf()
    {
        using var pack = new TempPack("cache", new Dictionary<string, string>());
        File.WriteAllBytes(Path.Combine(pack.Root, "bom.scriban"), [0xEF, 0xBB, 0xBF, (byte)'a', (byte)'\r', (byte)'\n', (byte)'b']);
