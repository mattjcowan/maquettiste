    [Fact]
    public void Templates_are_parsed_once_per_content_and_delimiters_and_read_once_per_run()
    {
        using var pack = new TempPack("cache", new Dictionary<string, string> { ["a.scriban"] = "A {{ 1 }}", ["./b.scriban"] = "B" });
        var loaded = pack.Load(RenderKit.Manifest("cache", new PackUnit { Id = "a", Template = "a.scriban", For = "model" }));
        var cache = new TemplateCache();

        var first = cache.Get(loaded, "a.scriban", null);
        Assert.Same(first, cache.Get(loaded, "./a.scriban", null));
        Assert.Same(first, cache.Get(loaded, "a.scriban", new Delimiters { Open = "{{", Close = "}}" }));
        var custom = cache.Get(loaded, "a.scriban", new Delimiters { Open = "<%", Close = "%>" });
        Assert.NotSame(first, custom);
        Assert.Equal(".maquettiste/templates/cache/a.scriban", cache.Describe(first)!.RepoPath);
        Assert.NotNull(cache.Describe(custom)!.Map);

        // Within a run the file is read once; a new run (a new cache) sees the change.
        pack.Write("a.scriban", "changed");
        Assert.Same(first, cache.Get(loaded, "a.scriban", null));
        Assert.Equal("changed", new TemplateCache().Get(loaded, "a.scriban", null).Render());
    }

    [Fact]
    public void Parse_failures_are_cached_and_reported_as_MQ6003()
    {
        using var pack = new TempPack("cache", new Dictionary<string, string> { ["bad.scriban"] = "\r\nline two {{ end }}" });
        var loaded = pack.Load(RenderKit.Manifest("cache", new PackUnit { Id = "a", Template = "bad.scriban", For = "model" }));
        var cache = new TemplateCache();
