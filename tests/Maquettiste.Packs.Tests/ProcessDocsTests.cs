    [Fact]
    public async Task Diagrams_give_repeated_and_reserved_names_path_ids_and_put_notes_inside_blocks()
    {
        using var repo = new DocsRepo("process-basics");
        repo.EditJson(".maquettiste/model/processes/order-lifecycle.json", process =>
        {
            // Billing.Paid becomes a second "Shipped" (Shipping has one) and Review.Escalated becomes "State", a keyword of the
            // diagram text; a targetless transition on Review.Pending gives the Review block a note, and one on the region Billing
            // of the parallel state Fulfilment gives that region a note inside its part of the parallel block.
            Rename(process["states"]!, "01JSTA00000000000000000013", "Shipped");
            Rename(process["states"]!, "01JSTA00000000000000000005", "State");
            process["transitions"]!.AsArray().Add(new JsonObject
            {
                ["id"] = "01JTRN0000000000000000P5D1",
                ["source"] = "01JSTA00000000000000000004",
                ["event"] = "01JPRX00000000000000000004",
                ["actions"] = new JsonArray("01JPRX00000000000000000022"),
            });
            process["transitions"]!.AsArray().Add(new JsonObject
            {
                ["id"] = "01JTRN0000000000000000P5D2",
                ["source"] = "01JSTA00000000000000000011",
                ["event"] = "01JPRX00000000000000000004",
                ["actions"] = new JsonArray("01JPRX00000000000000000022"),
            });
        });
        await repo.GenerateCleanlyAsync();

        var (path, text) = Assert.Single(DiagramsOf(repo));
        Assert.Equal("processes/order-lifecycle.md", path);
        var problems = DiagramText.Problems(text);
        Assert.True(problems.Count == 0, string.Join('\n', problems));
        Assert.Contains("            state \"Shipped\" as s_Fulfilment_Shipping_Shipped\n", text, StringComparison.Ordinal);
        Assert.Contains("            state \"Shipped\" as s_Fulfilment_Billing_Shipped\n", text, StringComparison.Ordinal);
        Assert.Contains("        state \"State\" as s_Review_State\n", text, StringComparison.Ordinal);
        Assert.Contains("        note right of Pending\n            internal: pay / notifyClerk\n        end note\n", text, StringComparison.Ordinal);
        Assert.Contains("    Decide --> s_Review_State : always [isLarge]\n", text, StringComparison.Ordinal);
        Assert.Matches(new Regex(@"\n        --\n        state Billing \{\n(?:            .*\n)*        \}\n        note right of Billing\n            internal: pay / notifyClerk\n        end note\n    \}\n"), text);
    }

