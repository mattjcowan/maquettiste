    [Fact]
    public void The_syntax_check_finds_broken_diagrams()
    {
        Assert.Empty(DiagramText.Problems("stateDiagram-v2\n    [*] --> A\n    A\n    state B {\n        [*] --> C\n        C\n    }\n    A --> B : go\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    state B {\n        C\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    A\n    }\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    A\n    A --> Z : go\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    A\n    A\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    --\n    A\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    A\n    A --> A : one; two\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram-v2\n    A\n    note right of A\n        x\n"));
        Assert.NotEmpty(DiagramText.Problems("stateDiagram\n    A\n"));
    }

    private static void Rename(JsonNode states, string id, string name)
    {
        foreach (var state in states.AsArray())
        {
            if ((string?)state!["id"] == id)
                state["name"] = name;
            if (state["states"] is { } children)
                Rename(children, id, name);
        }
    }

    /// <summary>The fenced diagram blocks of the generated pages, by page path under <c>docs/</c>.</summary>
    private static Dictionary<string, string> DiagramsOf(DocsRepo repo)
    {
        var diagrams = new Dictionary<string, string>(StringComparer.Ordinal);
        var root = repo.PathOf("docs");
        foreach (var file in Directory.EnumerateFiles(root, "*.md", SearchOption.AllDirectories).Order(StringComparer.Ordinal))
        {
            var text = File.ReadAllText(file);
            var start = text.IndexOf(DiagramFence, StringComparison.Ordinal);
            if (start < 0)
                continue;
            start += DiagramFence.Length;
            var end = text.IndexOf("\n```", start, StringComparison.Ordinal);
            Assert.True(end > start, file + ": the diagram block is not closed");
            Assert.Equal(-1, text.IndexOf(DiagramFence, end, StringComparison.Ordinal));
            diagrams[Path.GetRelativePath(root, file).Replace(Path.DirectorySeparatorChar, '/')] = text[start..(end + 1)];
        }

        return diagrams;
    }

    /// <summary>
    /// A small syntax check of the state diagram text the pack writes: the header line; every statement one of the forms the pack
    /// emits (a state, a quoted label as an id, a choice, a block opening or closing, a region separator inside a block, an edge,
    /// an edge from or to <c>[*]</c>, a note block); blocks balanced and notes closed; each id declared once (a quoted label may
    /// precede the block of the same id); every edge's and note's ends declared; one initial edge per block at most; and labels
    /// free of the characters that end a statement.
    /// </summary>
    internal static partial class DiagramText
    {
        public static IReadOnlyList<string> Problems(string text)
        {
            var problems = new List<string>();
            var lines = text.Split('\n');
            if (lines[0] != "stateDiagram-v2")
                problems.Add("the first line is not the diagram header");
            var declared = new Dictionary<string, string>(StringComparer.Ordinal);
            var referenced = new List<(int Line, string Id)>();
            var blocks = new Stack<(string Id, int Initials)>();
            var topInitials = 0;
            var inNote = false;
            for (var n = 1; n < lines.Length; n++)
            {
                var line = lines[n].Trim();
                if (line.Length == 0)
                    continue;
                if (inNote)
                {
                    if (line == "end note")
                        inNote = false;
                    else if (!Label(line))
                        problems.Add($"line {n + 1}: the note text holds a statement end");
                    continue;
                }

                Match m;
                if ((m = BlockOpen().Match(line)).Success)
                {
                    Declare(declared, m.Groups[1].Value, "block", n, problems);
                    blocks.Push((m.Groups[1].Value, 0));
                }
                else if (line == "}")
                {
                    if (blocks.Count == 0)
                        problems.Add($"line {n + 1}: a block closes that never opened");
                    else
                        blocks.Pop();
                }
                else if (line == "--")
                {
                    if (blocks.Count == 0)
                        problems.Add($"line {n + 1}: a region separator outside a block");
                }
                else if ((m = Choice().Match(line)).Success)
                    Declare(declared, m.Groups[1].Value, "state", n, problems);
                else if ((m = Labelled().Match(line)).Success)
                    Declare(declared, m.Groups[2].Value, "label", n, problems);
                else if ((m = Initial().Match(line)).Success)
                {
                    referenced.Add((n, m.Groups[1].Value));
                    if (blocks.Count == 0)
                        topInitials++;
                    else
                    {
                        var top = blocks.Pop();
                        blocks.Push((top.Id, top.Initials + 1));
                    }

                    if (topInitials > 1 || (blocks.Count > 0 && blocks.Peek().Initials > 1))
                        problems.Add($"line {n + 1}: a second initial edge in one block");
                }
                else if ((m = Final().Match(line)).Success)
                    referenced.Add((n, m.Groups[1].Value));
                else if ((m = Edge().Match(line)).Success)
                {
                    referenced.Add((n, m.Groups[1].Value));
                    referenced.Add((n, m.Groups[2].Value));
                    if (!Label(m.Groups[3].Value))
                        problems.Add($"line {n + 1}: the edge label holds a statement end");
                }
                else if ((m = Note().Match(line)).Success)
                {
                    referenced.Add((n, m.Groups[1].Value));
                    inNote = true;
                }
                else if (Id().IsMatch(line))
                    Declare(declared, line, "state", n, problems);
                else
                    problems.Add($"line {n + 1}: not a statement of the diagram: {line}");
            }

            if (blocks.Count > 0)
                problems.Add($"{blocks.Count} block(s) left open ({string.Join(", ", blocks.Select(b => b.Id))})");
            if (inNote)
                problems.Add("a note is left open");
            foreach (var (line, id) in referenced)
            {
                if (!declared.ContainsKey(id))
                    problems.Add($"line {line + 1}: '{id}' is not declared");
            }

            return problems;
        }

        private static void Declare(Dictionary<string, string> declared, string id, string how, int line, List<string> problems)
        {
            if (Reserved.Contains(id.ToLowerInvariant()))
                problems.Add($"line {line + 1}: '{id}' is a keyword of the diagram text");
            if (!declared.TryGetValue(id, out var before))
            {
                declared[id] = how;
                return;
            }

            // A quoted label names an id whose block follows; any other second declaration is a duplicate.
            if (before == "label" && how == "block")
                declared[id] = "block";
            else
                problems.Add($"line {line + 1}: '{id}' is declared twice");
        }

        // A label may hold entity codes (#35;) but no bare ';' or '#' and no double quote.
        private static bool Label(string text) => !BareEntity().IsMatch(text.Replace("\"", ";", StringComparison.Ordinal));

        private static readonly HashSet<string> Reserved =
        [
            "accdescr", "acctitle", "as", "class", "classdef", "click", "direction", "end", "hide", "href", "left", "note", "of", "right",
            "scale", "state", "style",
        ];

        [GeneratedRegex(@"^state ([A-Za-z_][A-Za-z0-9_]*) \{$")]
        private static partial Regex BlockOpen();

        [GeneratedRegex(@"^state ([A-Za-z_][A-Za-z0-9_]*) <<choice>>$")]
        private static partial Regex Choice();

        [GeneratedRegex("^state \"([^\"]+)\" as ([A-Za-z_][A-Za-z0-9_]*)$")]
        private static partial Regex Labelled();

        [GeneratedRegex(@"^\[\*\] --> ([A-Za-z_][A-Za-z0-9_]*)$")]
        private static partial Regex Initial();

        [GeneratedRegex(@"^([A-Za-z_][A-Za-z0-9_]*) --> \[\*\]$")]
        private static partial Regex Final();

        [GeneratedRegex(@"^([A-Za-z_][A-Za-z0-9_]*) --> ([A-Za-z_][A-Za-z0-9_]*) : (\S.*)$")]
        private static partial Regex Edge();

        [GeneratedRegex(@"^note right of ([A-Za-z_][A-Za-z0-9_]*)$")]
        private static partial Regex Note();

        [GeneratedRegex(@"^[A-Za-z_][A-Za-z0-9_]*$")]
        private static partial Regex Id();

        // A ';' that does not close an entity code, or a '#' that does not open one.
        [GeneratedRegex(@"(?<!#[A-Za-z0-9]+);|#(?![A-Za-z0-9]+;)")]
        private static partial Regex BareEntity();
    }

    /// <summary>A temporary repo holding one fixture model and the <c>process-docs</c> pack, writing to the committed root <c>docs</c>.</summary>
    private sealed class DocsRepo : IDisposable
    {
        public DocsRepo(string fixture)
        {
            Repo = new TempRepo();
            PackRepo.CopyTree(Fixtures.Path("models", fixture, ".maquettiste"), Repo.ModelRoot);
            PackRepo.CopyTree(Path.Combine(Fixtures.RepoRoot, "packs", "process-docs"), Path.Combine(Repo.ModelRoot, "templates", "process-docs"));
            // The gate 3 fixture registers the pack itself; another fixture gets the same registration here.
            EditJson(".maquettiste/maquettiste.json", settings =>
            {
                if (settings["packs"]?["process-docs"] is not null)
                    return;
                settings["outputs"] = JsonNode.Parse("""{ "allow": [ { "path": "docs", "commit": true } ] }""");
                settings["packs"] = JsonNode.Parse("""{ "process-docs": { "output": "docs" } }""");
            });
        }

        private TempRepo Repo { get; }

        public string PathOf(string path) => Repo.PathOf(path);

        public string Read(string path) => Repo.ReadFile(path);

        public void EditJson(string path, Action<JsonNode> edit)
        {
            var node = JsonNode.Parse(Repo.ReadFile(path))!;
            edit(node);
            Repo.WriteFile(path, node.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true }) + "\n");
        }

        public async Task<GenerationResult> GenerateAsync(GenerationMode mode = GenerationMode.Apply, int? jobs = null)
        {
            await using var store = new ModelStore(Repo.Options);
            var service = new GenerationService(store, Repo.Options);
            var request = new GenerationRequest { Mode = mode, Packs = ["process-docs"], Jobs = jobs };
            return await service.RunAsync(request, progress: null, TestContext.Current.CancellationToken);
        }

        public async Task<GenerationResult> GenerateCleanlyAsync(int? jobs = null)
        {
            var result = await GenerateAsync(GenerationMode.Apply, jobs);
            var errors = result.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
            Assert.True(result.Outcome == RunOutcome.Succeeded && errors.Count == 0, Describe(result));
            return result;
        }

        public static string Describe(GenerationResult result) => PackRepo.Describe(result);

        public void Dispose() => Repo.Dispose();
    }
