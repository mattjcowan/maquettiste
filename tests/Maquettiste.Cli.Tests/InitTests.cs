    }

    [Fact]
    public async Task Init_with_another_starter_pack_adds_its_output_entry_to_the_kept_settings()
    {
        using var repo = CliRepo.Empty();
        Assert.Equal(0, (await repo.RunAsync("init")).ExitCode);
        var second = await repo.RunAsync("init", "--pack", "csharp-dapper");
        Assert.True(second.ExitCode == 0, second.ToString());
        Assert.Contains("added packs.csharp-dapper.output", second.Error + second.Out, StringComparison.Ordinal);

        using var settings = JsonDocument.Parse(repo.Read(".maquettiste/maquettiste.json"));
        var packs = settings.RootElement.GetProperty("packs");
        Assert.Equal("db", packs.GetProperty("sql-ddl").GetProperty("output").GetString());
        Assert.Equal("src/Generated", packs.GetProperty("csharp-dapper").GetProperty("output").GetString());

        CliRepo.CopyTree(Fixtures.Path("models", "billing", ".maquettiste", "model"), repo.PathOf(".maquettiste/model"));
        var generate = await repo.RunAsync("generate");
        Assert.True(generate.ExitCode == 0, generate.ToString());
        Assert.NotEmpty(repo.Tree("src/Generated"));

        // A third run changes nothing.
        var before = repo.Read(".maquettiste/maquettiste.json");
        Assert.Equal(0, (await repo.RunAsync("init", "--pack", "csharp-dapper")).ExitCode);
        Assert.Equal(before, repo.Read(".maquettiste/maquettiste.json"));
    }

    [Fact]
    public async Task Init_refuses_a_gitignore_with_a_dangling_begin_marker_and_keeps_the_user_lines()
    {
        using var repo = CliRepo.Empty();
        const string text = "a\n# maquettiste:begin\nsecrets.env\nbar/\n";
        repo.Write(".gitignore", text);
        for (var i = 0; i < 2; i++)
        {
            var result = await repo.RunAsync("init", "--pack", "none");
            Assert.Equal(4, result.ExitCode);
