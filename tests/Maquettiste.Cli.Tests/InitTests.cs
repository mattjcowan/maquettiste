            Assert.Equal(text, repo.Read(".gitignore"));
        }

        Assert.False(File.Exists(repo.PathOf(".maquettiste/maquettiste.json")));
    }

    [Fact]
    public async Task Init_hooks_installs_executable_post_checkout_and_post_merge_hooks()
    {
        using var repo = CliRepo.Empty();
        Directory.CreateDirectory(repo.PathOf(".git/hooks"));
        var result = await repo.RunAsync("init", "--hooks");
        Assert.Equal(0, result.ExitCode);
        foreach (var hook in new[] { "post-checkout", "post-merge" })
        {
            var path = repo.PathOf(".git/hooks/" + hook);
            var text = File.ReadAllText(path);
            Assert.StartsWith("#!/bin/sh\n", text, StringComparison.Ordinal);
            Assert.Contains("generate --roots built --quiet", text, StringComparison.Ordinal);
            Assert.DoesNotContain('\r', text);
            if (!OperatingSystem.IsWindows())
                Assert.True(File.GetUnixFileMode(path).HasFlag(UnixFileMode.UserExecute));
        }

        // A foreign hook is kept; our own is rewritten.
        repo.Write(".git/hooks/post-merge", "#!/bin/sh\necho mine\n");
        var again = await repo.RunAsync("init", "--hooks");
        Assert.Equal(0, again.ExitCode);
        Assert.Equal("#!/bin/sh\necho mine\n", repo.Read(".git/hooks/post-merge"));
        Assert.Contains("kept .git/hooks/post-merge", again.Error, StringComparison.Ordinal);
    }

