    [Fact]
    public async Task Init_creates_the_layout_settings_schemas_starter_pack_and_gitignore_block()
    {
        using var repo = CliRepo.Empty();
        var result = await repo.RunAsync("init");
        Assert.Equal(0, result.ExitCode);
        Assert.Equal("", result.Out);

        foreach (var folder in InitCommand.Folders.Where(f => f != "templates"))
            Assert.True(File.Exists(repo.PathOf(".maquettiste/" + folder + "/.gitkeep")), folder);

        // Settings: canonical format 1 with the two default roots and the starter pack's output folder.
        var settings = repo.Read(".maquettiste/maquettiste.json");
        Assert.True(TestServices.Json.IsCanonical(Text.Utf8(settings), "maquettiste.json", "maquettiste.json"), settings);
        using (var doc = JsonDocument.Parse(settings))
        {
            var root = doc.RootElement;
            Assert.Equal(".schema/v1/maquettiste.json", root.GetProperty("$schema").GetString());
            Assert.Equal(1, root.GetProperty("formatVersion").GetInt32());
            var allow = root.GetProperty("outputs").GetProperty("allow").EnumerateArray().ToList();
            Assert.Equal("db", allow[0].GetProperty("path").GetString());
            Assert.True(allow[0].GetProperty("commit").GetBoolean());
            Assert.Equal("src/Generated", allow[1].GetProperty("path").GetString());
            Assert.False(allow[1].TryGetProperty("commit", out _));
            Assert.Equal("db", root.GetProperty("packs").GetProperty("sql-ddl").GetProperty("output").GetString());
        }

        // Every embedded schema, byte for byte.
        foreach (var name in TestServices.Schemas.FileNames)
            Assert.Equal(TestServices.Schemas.GetFileBytes(name).ToArray(), File.ReadAllBytes(repo.PathOf(".maquettiste/.schema/v1/" + name)));
        Assert.Equal(TestServices.Schemas.FileNames.Count, Directory.GetFiles(repo.PathOf(".maquettiste/.schema/v1")).Length);

        Assert.True(File.Exists(repo.PathOf(".maquettiste/templates/sql-ddl/pack.json")));
        Assert.False(File.Exists(repo.PathOf(".maquettiste/templates/.gitkeep")));

        var gitignore = repo.Read(".gitignore");
        Assert.Equal("# maquettiste:begin\n# Built output roots and the run journal; regenerated by maquettiste generate.\n/src/Generated/\n/.maquettiste/.cache/\n# maquettiste:end\n", gitignore);

        // The fresh repo validates cleanly.
        var validate = await repo.RunAsync("validate");
        Assert.Equal(0, validate.ExitCode);
    }

    [Fact]
    public async Task Init_is_idempotent_keeps_existing_files_and_refreshes_schemas()
    {
        using var repo = CliRepo.Empty();
        Directory.CreateDirectory(repo.RepoRoot);
        repo.Write(".gitignore", "bin/\nobj/\n");
        Assert.Equal(0, (await repo.RunAsync("init")).ExitCode);

        // Hand changes: settings with another built root, a pack template edit, a stale schema, a foreign schema file.
        repo.Replace(".maquettiste/maquettiste.json", "\"path\": \"src/Generated\"", "\"path\": \"gen/out\"");
        repo.Write(".maquettiste/templates/sql-ddl/table.scriban", "custom\n");
        repo.Write(".maquettiste/.schema/v1/entity.json", "{}\n");
        repo.Write(".maquettiste/.schema/v1/retired.json", "{}\n");
        repo.Write(".gitignore", repo.Read(".gitignore") + "*.log\n");

        var again = await repo.RunAsync("init");
        Assert.Equal(0, again.ExitCode);
        Assert.Contains("\"path\": \"gen/out\"", repo.Read(".maquettiste/maquettiste.json"), StringComparison.Ordinal);
        Assert.Equal("custom\n", repo.Read(".maquettiste/templates/sql-ddl/table.scriban"));
        Assert.Equal(TestServices.Schemas.GetFileBytes("entity.json").ToArray(), File.ReadAllBytes(repo.PathOf(".maquettiste/.schema/v1/entity.json")));
        Assert.False(File.Exists(repo.PathOf(".maquettiste/.schema/v1/retired.json")));

        // The block is rewritten in place from the current settings; the other lines stay.
        Assert.Equal(
            "bin/\nobj/\n\n# maquettiste:begin\n# Built output roots and the run journal; regenerated by maquettiste generate.\n/gen/out/\n/.maquettiste/.cache/\n# maquettiste:end\n*.log\n",
            repo.Read(".gitignore"));

        var third = await repo.RunAsync("init");
        Assert.Equal(0, third.ExitCode);
        Assert.Equal(1, repo.Read(".gitignore").Split("# maquettiste:begin").Length - 1);
    }

