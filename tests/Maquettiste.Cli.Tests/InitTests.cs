    [Fact]
    public async Task Init_refuses_a_gitignore_that_is_a_link_out_of_the_repo()
    {
        if (OperatingSystem.IsWindows())
            return;
        using var repo = CliRepo.Empty();
        Directory.CreateDirectory(repo.RepoRoot);
        var outside = Path.Combine(repo.Temp.Root, "outside.txt");
        File.WriteAllText(outside, "x\n");
