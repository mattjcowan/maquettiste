        var result = await repo.RunAsync("init");
        Assert.Equal(4, result.ExitCode);
        Assert.Contains("MQ6004", result.Error, StringComparison.Ordinal);
        Assert.Equal("x\n", File.ReadAllText(outside));
    }

    [Fact]
    public void Gitignore_block_is_replaced_in_place()
    {
        var text = InitCommand.WithBlock("a\n# maquettiste:begin\nold\n# maquettiste:end\nb\n", ["x", "/y/"]);
        Assert.Equal("a\n# maquettiste:begin\n# Built output roots and the run journal; regenerated by maquettiste generate.\n/x/\n/y/\n/.maquettiste/.cache/\n# maquettiste:end\nb\n", text);
        Assert.Equal(text, InitCommand.WithBlock(text, ["x", "/y/"]));
        Assert.StartsWith("# maquettiste:begin\n", InitCommand.WithBlock(null, []), StringComparison.Ordinal);
    }

    [Theory]
    [InlineData("a\n# maquettiste:begin\nsecrets.env\nbar/\n", "line 2: '# maquettiste:begin' has no matching")]
    [InlineData("a\n# maquettiste:end\nsecrets.env\n", "line 2: '# maquettiste:end' has no matching")]
    [InlineData("# maquettiste:end\nsecrets.env\n# maquettiste:begin\n", "line 1: '# maquettiste:end' has no matching")]
    [InlineData("# maquettiste:begin\nx\n# maquettiste:begin\ny\n# maquettiste:end\n", "line 3: '# maquettiste:begin' has no matching")]
    [InlineData("# maquettiste:begin\nx\n# maquettiste:end\ny\n# maquettiste:end\n", "line 5: '# maquettiste:end' has no matching")]
    public void Gitignore_block_with_malformed_markers_is_refused(string existing, string message)
    {
        // Run twice, as a second init would: the first refusal must not leave a state that the second run "repairs" by deleting lines.
        for (var i = 0; i < 2; i++)
        {
            var e = Assert.Throws<UsageException>(() => InitCommand.WithBlock(existing, ["x"]));
            Assert.Contains(message, e.Message, StringComparison.Ordinal);
        }
    }

