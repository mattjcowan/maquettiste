    [Fact]
    public async Task The_csharp_dapper_starter_output_compiles_with_nullable_and_warnings_as_errors()
    {
        using var repo = CliRepo.Empty();
        Assert.Equal(0, (await repo.RunAsync("init", "--pack", "csharp-dapper")).ExitCode);
        CliRepo.CopyTree(Fixtures.Path("models", "billing", ".maquettiste", "model"), repo.PathOf(".maquettiste/model"));
        var result = await repo.RunAsync("generate");
        Assert.True(result.ExitCode == 0, result.ToString());

        // The billing model's entities use an enum (InvoiceStatus) and a value object (Money): both must be generated too.
        var tree = repo.Tree("src/Generated");
        Assert.Contains("Billing/InvoiceStatus.g.cs", tree.Keys);
        Assert.Contains("Billing/Money.g.cs", tree.Keys);

        // Compile the generated folder as a net10.0 library (Nullable, ImplicitUsings, TreatWarningsAsErrors) with the SDK's compiler.
        var project = repo.PathOf("compile-check");
        CliRepo.CopyTree(repo.PathOf("src/Generated"), project);
        await File.WriteAllTextAsync(Path.Combine(project, "Check.csproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <Nullable>enable</Nullable>
                <ImplicitUsings>enable</ImplicitUsings>
                <TreatWarningsAsErrors>true</TreatWarningsAsErrors>
              </PropertyGroup>
              <ItemGroup>
                <!-- The embedded csharp-dapper pack generates Dapper repositories and type handlers. -->
                <PackageReference Include="Dapper" Version="2.1.66" />
              </ItemGroup>
            </Project>
            """, TestContext.Current.CancellationToken);
        var (code, output) = await DotnetAsync(project, "build", "-nologo", "-nodeReuse:false", "-p:UseSharedCompilation=false", "-clp:NoSummary");
        Assert.True(code == 0, output);
        Assert.DoesNotContain(": error ", output, StringComparison.Ordinal);
        Assert.DoesNotContain(": warning ", output, StringComparison.Ordinal);
    }

    private static async Task<(int Code, string Output)> DotnetAsync(string cwd, params string[] args)
    {
        var host = Environment.ProcessPath is { } p && Path.GetFileNameWithoutExtension(p) == "dotnet" ? p : "dotnet";
        var start = new System.Diagnostics.ProcessStartInfo(host)
        {
            WorkingDirectory = cwd,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
        };
        foreach (var arg in args)
            start.ArgumentList.Add(arg);
        // The test host's MSBuild settings would point the child build at this repo's build; it gets a clean environment instead.
        foreach (var name in start.Environment.Keys.Where(k => k.StartsWith("MSBUILD", StringComparison.OrdinalIgnoreCase) || k.StartsWith("VSTEST", StringComparison.OrdinalIgnoreCase)).ToList())
            start.Environment.Remove(name);
        start.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
        start.Environment["DOTNET_NOLOGO"] = "1";
        using var cts = CancellationTokenSource.CreateLinkedTokenSource(TestContext.Current.CancellationToken);
        cts.CancelAfter(TimeSpan.FromMinutes(3));
        using var process = System.Diagnostics.Process.Start(start)!;
        var stdout = process.StandardOutput.ReadToEndAsync(cts.Token);
        var stderr = process.StandardError.ReadToEndAsync(cts.Token);
        await process.WaitForExitAsync(cts.Token);
        return (process.ExitCode, await stdout + await stderr);
    }

    [Theory]
