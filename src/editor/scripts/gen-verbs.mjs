#!/usr/bin/env node
// Writes src/model/verbs.ts: the built-in verbs (verbs-design.md decision 1) from the engine's one table,
// src/Maquettiste.Engine/Model/BuiltInVerbs.cs, with the verbs left to projects that "Add a verb…" suggests. The output is committed;
// `--check` exits 1 when it differs from the engine's table. BuiltInVerbsTests checks the same agreement from the engine side.
import fs from "node:fs";
import path from "node:path";
import { editorRoot, repoRoot } from "./paths.mjs";

const source = fs.readFileSync(path.join(repoRoot, "src/Maquettiste.Engine/Model/BuiltInVerbs.cs"), "utf8");
const output = path.join(editorRoot, "src/model/verbs.ts");

const verbs = [...source.matchAll(/new\("([a-z0-9-]+)", "([^"]+)", "([a-z]+)", "((?:[^"\\]|\\.)*)"\)/g)].map((m) => ({
  key: m[1],
  displayName: m[2],
  group: m[3],
  meaning: m[4].replace(/\\"/g, '"'),
}));
const groups =
  /Groups \{ get; \} = \[([^\]]*)\]/
    .exec(source)?.[1]
    .match(/"([a-z]+)"/g)
    ?.map((g) => g.slice(1, -1)) ?? [];
const suggestions =
  /Suggestions \{ get; \} =\s*\[([^\]]*)\]/
    .exec(source)?.[1]
    .match(/"([a-z0-9-]+)"/g)
    ?.map((s) => s.slice(1, -1)) ?? [];
if (verbs.length === 0 || groups.length === 0 || suggestions.length === 0) throw new Error("Could not read the engine's table of built-in verbs.");

const q = (s) => JSON.stringify(s);
const text = `// Generated by scripts/gen-verbs.mjs from src/Maquettiste.Engine/Model/BuiltInVerbs.cs. Do not edit; run \`npm run gen\`.

/** What a built-in verb acts on (verbs-design.md decision 4). */
export type BuiltInVerbGroup = ${groups.map(q).join(" | ")};

/** A built-in verb: a fixed key, label, group and meaning that never change (verbs-design.md decision 1). */
export interface BuiltInVerb {
  key: string;
  displayName: string;
  group: BuiltInVerbGroup;
  meaning: string;
}

/** The groups, in the order pickers and the docs list them. */
export const builtInVerbGroups: readonly BuiltInVerbGroup[] = [${groups.map(q).join(", ")}];

/** Every built-in verb, in the engine's table order. */
export const builtInVerbs: readonly BuiltInVerb[] = [
${verbs.map((v) => `  { key: ${q(v.key)}, displayName: ${q(v.displayName)}, group: ${q(v.group)}, meaning: ${q(v.meaning)} },`).join("\n")}
];

/** Verbs left to projects, which "Add a verb…" offers as suggestions that only pre-fill an own verb (verbs-design.md decision 7). */
export const suggestedVerbKeys: readonly string[] = [${suggestions.map(q).join(", ")}];
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
  if (current !== text) {
    console.error("src/model/verbs.ts is out of date with the engine's table of built-in verbs. Run `npm run gen` and commit the result.");
    process.exit(1);
  }
} else {
  fs.writeFileSync(output, text);
}
